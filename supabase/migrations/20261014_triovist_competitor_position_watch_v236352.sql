CREATE OR REPLACE FUNCTION public.triovist_market_competitor_position_history_v236352(p_scope_key text, p_product_key text, p_days integer DEFAULT 30)
 RETURNS jsonb
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO 'public', 'auth', 'pg_catalog'
AS $function$
declare
  a record;
  v_scope text:=btrim(coalesce(p_scope_key,''));
  v_product text:=btrim(coalesce(p_product_key,''));
  v_days integer:=least(greatest(coalesce(p_days,30),1),30);
  v_current record;
  v_rows jsonb;
  v_summary jsonb;
begin
  select * into a from public.triovist_content_actor();
  if a.actor_email is null or a.actor_email not in (
    'payushin_ar@resanta.ru','sidarovich_kn@resanta.ru',
    'aleksandrenko_av@resanta.ru','krishtal_na@resanta.ru'
  ) then
    raise exception 'Нет доступа к истории конкурента 21vek' using errcode='42501';
  end if;
  if v_scope='' or v_product='' then
    raise exception 'Не передан конкурент' using errcode='22023';
  end if;

  select * into v_current
  from public.triovist_market_comp_position_current_v236352
  where scope_key=v_scope and product_key=v_product;

  with timeline as (
    select
      s.observed_at,s.position,
      case when s.position between 1 and 120 then 'top120'::text else 'top120'::text end listing_state,
      s.current_price,s.in_stock,
      'success'::text attempt_status,null::text error_text,
      'full_market'::text source
    from public.triovist_market_product_snapshots_v1 s
    where s.scope_key=v_scope and s.product_key=v_product
      and s.error_text is null
      and s.observed_at >= now()-make_interval(days=>v_days)
    union all
    select
      s.observed_at,s.position,s.listing_state,s.current_price,s.in_stock,
      s.attempt_status,s.error_text,s.source
    from public.triovist_market_comp_position_snapshots_v236352 s
    where s.scope_key=v_scope and s.product_key=v_product
      and s.observed_at >= now()-make_interval(days=>v_days)
  ),
  success_t as (
    select * from timeline
    where attempt_status='success'
  ),
  thresholds as (
    select
      (select case when x.listing_state='top120' and x.position is not null then x.position::text else '>120' end
       from success_t x where x.observed_at <= coalesce(v_current.observed_at,now())-interval '1 day'
       order by x.observed_at desc limit 1) p1,
      (select case when x.listing_state='top120' and x.position is not null then x.position::text else '>120' end
       from success_t x where x.observed_at <= coalesce(v_current.observed_at,now())-interval '3 days'
       order by x.observed_at desc limit 1) p3,
      (select case when x.listing_state='top120' and x.position is not null then x.position::text else '>120' end
       from success_t x where x.observed_at <= coalesce(v_current.observed_at,now())-interval '7 days'
       order by x.observed_at desc limit 1) p7,
      (select case when x.listing_state='top120' and x.position is not null then x.position::text else '>120' end
       from success_t x where x.observed_at <= coalesce(v_current.observed_at,now())-interval '14 days'
       order by x.observed_at desc limit 1) p14,
      (select case when x.listing_state='top120' and x.position is not null then x.position::text else '>120' end
       from success_t x where x.observed_at <= coalesce(v_current.observed_at,now())-interval '30 days'
       order by x.observed_at desc limit 1) p30,
      min(position) filter(where listing_state='top120' and position is not null) best,
      case when bool_or(listing_state='outside_top120') then '>120'
           else max(position) filter(where listing_state='top120' and position is not null)::text end worst
    from success_t
  )
  select jsonb_build_object(
    'position_1d',coalesce(p1,'—'),
    'position_3d',coalesce(p3,'—'),
    'position_7d',coalesce(p7,'—'),
    'position_14d',coalesce(p14,'—'),
    'position_30d',coalesce(p30,'—'),
    'best',best,
    'worst',coalesce(worst,'—')
  ) into v_summary
  from thresholds;

  with timeline as (
    select
      s.observed_at,s.position,'top120'::text listing_state,s.current_price,s.in_stock,
      'success'::text attempt_status,null::text error_text,'full_market'::text source
    from public.triovist_market_product_snapshots_v1 s
    where s.scope_key=v_scope and s.product_key=v_product
      and s.error_text is null
      and s.observed_at >= now()-make_interval(days=>v_days)
    union all
    select
      s.observed_at,s.position,s.listing_state,s.current_price,s.in_stock,
      s.attempt_status,s.error_text,s.source
    from public.triovist_market_comp_position_snapshots_v236352 s
    where s.scope_key=v_scope and s.product_key=v_product
      and s.observed_at >= now()-make_interval(days=>v_days)
  )
  select coalesce(jsonb_agg(jsonb_build_object(
    'observed_at',t.observed_at,
    'position',t.position,
    'position_label',case
      when t.attempt_status='error' then 'Ошибка'
      when t.listing_state='outside_top120' then '>120'
      when t.position is not null then t.position::text
      else '—'
    end,
    'listing_state',t.listing_state,
    'current_price',t.current_price,
    'in_stock',t.in_stock,
    'attempt_status',t.attempt_status,
    'error_text',t.error_text,
    'source',t.source
  ) order by t.observed_at),'[]'::jsonb)
  into v_rows
  from timeline t;

  return jsonb_build_object(
    'version','v23.6.352',
    'days',v_days,
    'current',case when v_current.scope_key is null then null else jsonb_build_object(
      'scope_key',v_current.scope_key,'product_key',v_current.product_key,
      'search_query',v_current.search_query,'brand',v_current.brand,'model',v_current.model,
      'position',v_current.position,'listing_state',v_current.listing_state,
      'current_price',v_current.current_price,'in_stock',v_current.in_stock,
      'observed_at',v_current.observed_at,'previous_position',v_current.previous_position,
      'previous_state',v_current.previous_state,'previous_observed_at',v_current.previous_observed_at,
      'position_delta',v_current.position_delta,'movement',v_current.movement,
      'changed_at',v_current.changed_at,'last_attempt_at',v_current.last_attempt_at,
      'last_attempt_status',v_current.last_attempt_status,'last_error',v_current.last_error
    ) end,
    'summary',coalesce(v_summary,'{}'::jsonb),
    'rows',v_rows,
    'change_semantics','Позиция фиксируется новым запросом к 21vek. Если запрос не удался, старое успешное значение не становится свежим.'
  );
end;
$function$;

CREATE OR REPLACE FUNCTION public.triovist_market_competitor_positions_v236352(p_scope_key text DEFAULT NULL::text)
 RETURNS jsonb
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO 'public', 'auth', 'pg_catalog'
AS $function$
declare
  a record;
  v_scope text:=btrim(coalesce(p_scope_key,''));
  v_rows jsonb;
  v_last_run jsonb;
begin
  select * into a from public.triovist_content_actor();
  if a.actor_email is null or a.actor_email not in (
    'payushin_ar@resanta.ru','sidarovich_kn@resanta.ru',
    'aleksandrenko_av@resanta.ru','krishtal_na@resanta.ru'
  ) then
    raise exception 'Нет доступа к конкурентам 21vek' using errcode='42501';
  end if;

  select coalesce(jsonb_agg(jsonb_build_object(
    'scope_key',c.scope_key,
    'product_key',c.product_key,
    'search_query',c.search_query,
    'brand',c.brand,
    'model',c.model,
    'position',c.position,
    'page_no',c.page_no,
    'listing_state',c.listing_state,
    'current_price',c.current_price,
    'in_stock',c.in_stock,
    'observed_at',c.observed_at,
    'previous_position',c.previous_position,
    'previous_state',c.previous_state,
    'previous_observed_at',c.previous_observed_at,
    'position_delta',c.position_delta,
    'movement',c.movement,
    'changed_at',c.changed_at,
    'last_attempt_at',c.last_attempt_at,
    'last_attempt_status',c.last_attempt_status,
    'last_error',c.last_error,
    'freshness_minutes',greatest(0,floor(extract(epoch from (now()-c.observed_at))/60))::int,
    'freshness',case
      when now()-c.observed_at <= interval '4 hours' then 'fresh'
      when now()-c.observed_at <= interval '8 hours' then 'aging'
      else 'stale'
    end
  ) order by c.scope_key,c.position nulls last,c.product_key),'[]'::jsonb)
  into v_rows
  from public.triovist_market_comp_position_current_v236352 c
  where v_scope='' or c.scope_key=v_scope;

  select to_jsonb(r) into v_last_run
  from (
    select id,source,status,scope_count,query_count,tracked_count,success_count,error_count,started_at,finished_at
    from public.triovist_market_position_watch_runs_v236352
    where status in ('complete','partial','failed')
    order by started_at desc
    limit 1
  ) r;

  return jsonb_build_object(
    'version','v23.6.352',
    'position_depth',120,
    'refresh_target_hours',3,
    'rows',v_rows,
    'last_run',v_last_run,
    'freshness_rules',jsonb_build_object('fresh_hours',4,'aging_hours',8)
  );
end;
$function$;

