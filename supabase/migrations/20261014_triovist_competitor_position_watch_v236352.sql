create table if not exists public.triovist_market_position_watch_runs_v236352 (
  id uuid primary key default gen_random_uuid(),
  source text not null default 'schedule' check(source in ('schedule','manual','test')),
  status text not null default 'running' check(status in ('running','complete','partial','failed')),
  scope_count integer not null default 0,
