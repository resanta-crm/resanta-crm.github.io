      case when v_over>0
           then 'Осознанно согласовано превышение бюджета на '||round(v_over,2)||' BYN' end
    )
  );

  return jsonb_build_object(
    'ok',true,'promotion_id',v_p.id,'budget_id',v_b.id,'reserved',v_amount,
    'free_before',v_free,'free_after',v_free-v_amount,'client_name',v_p.client_name,
