CREATE OR REPLACE FUNCTION public.crm_promotions_quantity_control_v236375(p_promotion_id uuid DEFAULT NULL::uuid)
 RETURNS jsonb
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO 'public', 'auth', 'pg_catalog'
AS $function$
declare
  v_actor public.users%rowtype;
  p public.promotions%rowtype;
  i public.promotion_items%rowtype;
  v_rows jsonb:='[]'::jsonb;
  v_items jsonb;
  v_tracking_start date;
  v_target_date date;
  v_month date;
  v_month_end date;
  v_seg_start date;
  v_seg_end date;
  v_base numeric;
  v_end numeric;
  v_fact numeric;
  v_calendar numeric;
  v_item_exact boolean;
  v_all_exact boolean;
  v_item_source text;
  v_manual numeric;
  v_manual_by text;
  v_manual_at timestamptz;
  v_planned_total numeric;
  v_fact_total numeric;
  v_item_count int;
  v_qty_filled int;
  v_baseline_qty numeric;
  v_target_qty numeric;
  v_historical boolean;
  v_completion numeric;
  v_growth_completion numeric;
  v_cutoff timestamptz:='2026-10-15 00:00:00+03'::timestamptz;
begin
  select * into v_actor from public.users where id=auth.uid();
  if v_actor.id is null then raise exception 'Требуется вход в CRM' using errcode='42501'; end if;

  for p in
    select x.*
    from public.promotions x
    where (p_promotion_id is null or x.id=p_promotion_id)
      and (
        coalesce(v_actor.role,'')='boss'
        or lower(trim(coalesce(x.manager_name,'')))=lower(trim(coalesce(v_actor.name,'')))
      )
    order by x.start_date desc,x.created_at desc
  loop
    v_historical := p.status='completed' and p.created_at<v_cutoff;
    v_tracking_start := coalesce((p.approved_at at time zone 'Europe/Minsk')::date,p.start_date);
    v_target_date := least(current_date,p.end_date);
    v_items:='[]'::jsonb;
    v_planned_total:=0;
    v_fact_total:=0;
    v_item_count:=0;
    v_qty_filled:=0;
    v_all_exact:=true;

    begin
      v_baseline_qty:=nullif(p.ai_precheck->>'baseline_qty','')::numeric;
    exception when others then
      v_baseline_qty:=null;
    end;
    begin
      v_target_qty:=nullif(p.ai_precheck->>'target_qty_30','')::numeric;
    exception when others then
      v_target_qty:=null;
    end;
    if v_target_qty is null and coalesce(v_baseline_qty,0)>0 then
      v_target_qty:=ceil(v_baseline_qty*1.30);
    end if;

    for i in
      select *
      from public.promotion_items pi
      where pi.promotion_id=p.id
      order by pi.sku
    loop
      v_item_count:=v_item_count+1;
      if coalesce(i.planned_qty,0)>0 then
        v_qty_filled:=v_qty_filled+1;
        v_planned_total:=v_planned_total+i.planned_qty;
      end if;

      select coalesce(sum(h.qty),0)
      into v_calendar
      from public.purchase_history h
      where h.client_id=p.client_id
        and trim(coalesce(h.sku,''))=trim(coalesce(i.sku,''))
        and h.month between date_trunc('month',v_tracking_start)::date
                        and date_trunc('month',least(current_date,p.end_date))::date;

      select r.confirmed_qty,r.confirmed_by,r.confirmed_at
      into v_manual,v_manual_by,v_manual_at
      from public.promotion_quantity_results r
      where r.promotion_id=p.id and trim(r.sku)=trim(i.sku);

      if v_historical then
        v_fact:=v_calendar;
        v_item_exact:=false;
        v_item_source:='historical_calendar';
      elsif v_manual is not null then
        v_fact:=v_manual;
        v_item_exact:=true;
        v_item_source:='manual_confirmed';
      elsif current_date<v_tracking_start then
        v_fact:=0;
        v_item_exact:=true;
        v_item_source:='future';
      else
        v_fact:=0;
        v_item_exact:=true;
        v_month:=date_trunc('month',v_tracking_start)::date;

        while v_month<=date_trunc('month',v_target_date)::date loop
          v_month_end:=(v_month+interval '1 month - 1 day')::date;
          v_seg_start:=greatest(v_tracking_start,v_month);
          v_seg_end:=least(v_target_date,v_month_end);

          if v_seg_start>v_seg_end then
            v_month:=(v_month+interval '1 month')::date;
            continue;
          end if;

          if v_seg_start=v_month then
            v_base:=0;
          else
            v_base:=null;
            if p.approved_at is not null
               and v_month=date_trunc('month',(p.approved_at at time zone 'Europe/Minsk'))::date then
              select s.cumulative_qty
              into v_base
              from public.promotion_sku_sales_snapshots s
              where s.promotion_id=p.id
                and trim(s.sku)=trim(i.sku)
                and s.snapshot_kind='approval_baseline'
                and s.report_month=v_month
              order by s.snapshot_at desc
              limit 1;
            end if;

            if v_base is null then
              select s.cumulative_qty
              into v_base
              from public.promotion_sku_sales_snapshots s
              where s.promotion_id=p.id
                and trim(s.sku)=trim(i.sku)
                and s.report_month=v_month
                and s.snapshot_kind in ('periodic','backfill_baseline','manual')
                and (s.snapshot_at at time zone 'Europe/Minsk')::date<v_seg_start
              order by s.snapshot_at desc
              limit 1;
            end if;

            if v_base is null then
              v_item_exact:=false;
            end if;
          end if;

          v_end:=null;
          if v_seg_end=v_month_end and v_seg_end<current_date then
            select coalesce(sum(h.qty),0)
            into v_end
            from public.purchase_history h
            where h.client_id=p.client_id
              and trim(coalesce(h.sku,''))=trim(coalesce(i.sku,''))
              and h.month=v_month;
          elsif v_seg_end=current_date and current_date<=p.end_date then
            select coalesce(sum(h.qty),0)
            into v_end
            from public.purchase_history h
            where h.client_id=p.client_id
              and trim(coalesce(h.sku,''))=trim(coalesce(i.sku,''))
              and h.month=v_month;
          else
            select s.cumulative_qty
            into v_end
            from public.promotion_sku_sales_snapshots s
            where s.promotion_id=p.id
              and trim(s.sku)=trim(i.sku)
              and s.report_month=v_month
              and s.snapshot_kind='periodic'
              and (s.snapshot_at at time zone 'Europe/Minsk')::date=v_seg_end
            order by s.snapshot_at desc
            limit 1;
            if v_end is null then
              v_item_exact:=false;
            end if;
          end if;

          if v_item_exact then
            v_fact:=v_fact+greatest(0,coalesce(v_end,0)-coalesce(v_base,0));
          end if;

          v_month:=(v_month+interval '1 month')::date;
        end loop;

        if not v_item_exact then
          v_fact:=v_calendar;
          v_item_source:='calendar_preliminary';
        else
          v_item_source:='1c_exact_qty';
        end if;
      end if;

      v_all_exact:=v_all_exact and v_item_exact;
      v_fact_total:=v_fact_total+coalesce(v_fact,0);

      v_items:=v_items||jsonb_build_array(jsonb_build_object(
        'sku',i.sku,
        'product_name',i.product_name,
        'planned_qty',i.planned_qty,
        'fact_qty',round(coalesce(v_fact,0),2),
        'calendar_qty',round(coalesce(v_calendar,0),2),
        'quantity_exact',v_item_exact,
        'source',v_item_source,
        'manual_confirmed_by',v_manual_by,
        'manual_confirmed_at',v_manual_at,
        'completion_pct',case when coalesce(i.planned_qty,0)>0
                              then round(coalesce(v_fact,0)/i.planned_qty*100,1)
                              else null end
      ));
    end loop;

    v_completion:=case when v_planned_total>0 then round(v_fact_total/v_planned_total*100,1) else null end;
    v_growth_completion:=case when coalesce(v_target_qty,0)>0 then round(v_fact_total/v_target_qty*100,1) else null end;

    v_rows:=v_rows||jsonb_build_array(jsonb_build_object(
      'promotion_id',p.id,
      'status',p.status,
      'client_name',p.client_name,
      'manager_name',p.manager_name,
      'title',p.title,
      'created_at',p.created_at,
      'approved_at',p.approved_at,
      'start_date',p.start_date,
      'end_date',p.end_date,
      'tracking_start_date',v_tracking_start,
      'historical_mode',v_historical,
      'quantity_mode_cutoff',v_cutoff,
      'item_count',v_item_count,
      'quantity_filled_count',v_qty_filled,
      'quantity_complete',(v_item_count>0 and v_item_count=v_qty_filled),
      'planned_qty_total',round(v_planned_total,2),
      'fact_qty_total',round(v_fact_total,2),
      'quantity_exact',(v_item_count>0 and v_all_exact),
      'completion_pct',v_completion,
      'baseline_qty',v_baseline_qty,
      'target_qty_30',v_target_qty,
      'target_growth_pct',30,
      'target_completion_pct',v_growth_completion,
      'target_met',(v_item_count>0 and v_all_exact and coalesce(v_target_qty,0)>0 and v_fact_total>=v_target_qty),
      'items',v_items
    ));
  end loop;

  return v_rows;
end;
$function$;

CREATE OR REPLACE FUNCTION public.crm_promotion_update_planned_qty_v236375(p_promotion_id uuid, p_items jsonb)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'auth', 'pg_catalog'
AS $function$
declare
  v_actor public.users%rowtype;
  v_p public.promotions%rowtype;
  x jsonb;
  v_sku text;
  v_qty integer;
  v_old integer;
  v_changed int:=0;
  v_lines text[]:=array[]::text[];
  v_is_boss boolean:=false;
  v_owner boolean:=false;
begin
  select * into v_actor from public.users where id=auth.uid();
  if v_actor.id is null then raise exception 'Требуется вход в CRM' using errcode='42501'; end if;

  select * into v_p from public.promotions where id=p_promotion_id for update;
  if v_p.id is null then raise exception 'Акция не найдена'; end if;

  v_is_boss:=coalesce(v_actor.role,'')='boss';
  v_owner:=lower(trim(coalesce(v_actor.name,'')))=lower(trim(coalesce(v_p.manager_name,'')));

  if not v_is_boss and not v_owner then
    raise exception 'Нет доступа к количеству этой акции' using errcode='42501';
  end if;
  if v_p.status in ('completed','rejected') then
    raise exception 'Завершённую или отклонённую акцию изменять нельзя';
  end if;
  if jsonb_typeof(p_items)<>'array' then
    raise exception 'Неверный формат количества';
  end if;

  for x in select value from jsonb_array_elements(p_items)
  loop
    v_sku:=trim(coalesce(x->>'sku',''));
    begin
      v_qty:=round((x->>'planned_qty')::numeric)::integer;
    exception when others then
      v_qty:=null;
    end;
    if v_sku='' or v_qty is null or v_qty<=0 then
      raise exception 'По каждому SKU нужно указать количество больше 0';
    end if;

    select planned_qty into v_old
    from public.promotion_items
    where promotion_id=v_p.id and trim(sku)=v_sku
    for update;
    if not found then raise exception 'SKU % не найден в акции',v_sku; end if;

    if not v_is_boss
       and v_p.status in ('pending_dfs','approved','in_work')
       and v_old is not null
       and v_old<>v_qty then
      raise exception 'После согласования менеджер может только заполнить ранее пустое количество. Изменить уже согласованное количество по SKU % может руководитель.',v_sku;
    end if;

    if v_old is distinct from v_qty then
      update public.promotion_items
      set planned_qty=v_qty,updated_at=now()
      where promotion_id=v_p.id and trim(sku)=v_sku;
      v_changed:=v_changed+1;
      v_lines:=array_append(v_lines,v_sku||': '||coalesce(v_old::text,'—')||' → '||v_qty::text||' шт.');
    end if;
  end loop;

  if v_changed>0 then
    update public.promotions set updated_at=now() where id=v_p.id;
    insert into public.promotion_approval_audit(promotion_id,stage,action,actor,comment)
    values(
      v_p.id,'quantity','update_planned_qty',
      coalesce(v_actor.name,v_actor.email),
      'Количество по SKU: '||array_to_string(v_lines,'; ')
    );
  end if;

  return jsonb_build_object('ok',true,'promotion_id',v_p.id,'changed',v_changed);
end;
$function$;

CREATE OR REPLACE FUNCTION public.crm_promotion_confirm_quantity_v236375(p_promotion_id uuid, p_items jsonb, p_note text DEFAULT NULL::text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'auth', 'pg_catalog'
AS $function$
declare
  v_actor public.users%rowtype;
  v_p public.promotions%rowtype;
  x jsonb;
  v_sku text;
  v_qty numeric;
  v_count int:=0;
begin
  select * into v_actor from public.users where id=auth.uid();
  if v_actor.id is null
     or coalesce(v_actor.role,'')<>'boss'
     or lower(coalesce(v_actor.email,''))<>'payushin_ar@resanta.ru' then
    raise exception 'Ручной итог количества может подтвердить только Александр Паюшин' using errcode='42501';
  end if;

  select * into v_p from public.promotions where id=p_promotion_id;
  if v_p.id is null then raise exception 'Акция не найдена'; end if;
  if jsonb_typeof(p_items)<>'array' then raise exception 'Неверный формат количества'; end if;

  for x in select value from jsonb_array_elements(p_items)
  loop
    v_sku:=trim(coalesce(x->>'sku',''));
    begin
      v_qty:=(x->>'confirmed_qty')::numeric;
    exception when others then
      v_qty:=null;
    end;
    if v_sku='' or v_qty is null or v_qty<0 then
      raise exception 'По каждому SKU укажите подтверждённый факт 0 или больше';
    end if;
    if not exists(
      select 1 from public.promotion_items i
      where i.promotion_id=v_p.id and trim(i.sku)=v_sku
    ) then
      raise exception 'SKU % не найден в акции',v_sku;
    end if;

    insert into public.promotion_quantity_results(
      promotion_id,sku,confirmed_qty,confirmed_by,confirmed_at,source,note
    )
    values(v_p.id,v_sku,v_qty,v_actor.name,now(),'manual_close',nullif(trim(coalesce(p_note,'')),''))
    on conflict(promotion_id,sku) do update set
      confirmed_qty=excluded.confirmed_qty,
      confirmed_by=excluded.confirmed_by,
      confirmed_at=excluded.confirmed_at,
      source=excluded.source,
      note=excluded.note;
    v_count:=v_count+1;
  end loop;

  insert into public.promotion_approval_audit(promotion_id,stage,action,actor,comment)
  values(
    v_p.id,'quantity','confirm_actual_qty',v_actor.name,
    concat('Ручной факт количества подтверждён по ',v_count,' SKU',
      case when nullif(trim(coalesce(p_note,'')),'') is not null then ': '||trim(p_note) else '' end)
  );

  return jsonb_build_object('ok',true,'promotion_id',v_p.id,'confirmed_items',v_count);
end;
$function$;

