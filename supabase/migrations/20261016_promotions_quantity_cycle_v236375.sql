CREATE OR REPLACE FUNCTION public.crm_promotions_autolink_budget_v23630()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'pg_catalog'
AS $function$
declare
  v_budget_id uuid;
  v_budget_client uuid;
  v_budget_name text;
  v_client_name text;
  v_legal_key text;
begin
  if new.client_id is null then
    return new;
  end if;

  v_client_name:=coalesce(
    nullif(trim(new.client_name),''),
    (select c.name from public.clients c where c.id=new.client_id)
  );
  v_legal_key:=public.crm_client_legal_key_v236374(v_client_name);

  select b.id into v_budget_id
  from public.promotion_budgets b
  where b.client_id=new.client_id
     or (
       v_legal_key<>''
       and public.crm_client_legal_key_v236374(b.client_name)=v_legal_key
     )
  order by
    case when b.client_id=new.client_id then 0 else 1 end,
    coalesce(b.balance_snapshot_at,b.updated_at,b.created_at) desc nulls last
  limit 1;

  if new.budget_id is null then
    new.budget_id:=v_budget_id;
    return new;
  end if;

  select b.client_id,b.client_name into v_budget_client,v_budget_name
  from public.promotion_budgets b
  where b.id=new.budget_id;

  if v_budget_client is null then
    raise exception 'Бюджет акции не найден';
  end if;

  if v_budget_client is distinct from new.client_id
     and (
       v_legal_key=''
       or public.crm_client_legal_key_v236374(v_budget_name)<>v_legal_key
     ) then
    raise exception 'Нельзя использовать бюджет другого юрлица';
  end if;

  return new;
end;
$function$;

CREATE OR REPLACE FUNCTION public.promotion_capture_sales_snapshots_v23654(p_report_month date, p_source_message_at timestamp with time zone DEFAULT NULL::timestamp with time zone)
 RETURNS integer
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'pg_catalog'
AS $function$
declare
  v_month date := date_trunc('month',p_report_month)::date;
  v_month_end date := (date_trunc('month',p_report_month)+interval '1 month - 1 day')::date;
  v_snapshot_at timestamptz := coalesce(p_source_message_at,now());
  v_count integer := 0;
begin
  insert into public.promotion_sales_snapshots(
    promotion_id,snapshot_at,report_month,cumulative_sales,cumulative_qty,source_message_at,scope_version
  )
  select
    p.id,
    v_snapshot_at,
    v_month,
    coalesce(sum(ph.revenue),0)::numeric(16,2),
    coalesce(sum(ph.qty),0)::numeric(16,2),
    p_source_message_at,
    case
      when exists(
        select 1 from public.promotion_items i
        where i.promotion_id=p.id and trim(coalesce(i.sku,''))<>''
      ) then 'exact_sku_qty_v236375'
      else 'legacy_filter'
    end
  from public.promotions p
  left join public.purchase_history ph
    on ph.month=v_month
   and (
        (p.client_id is not null and ph.client_id=p.client_id)
        or lower(trim(coalesce(ph.client_name,'')))=lower(trim(coalesce(p.client_name,'')))
   )
   and (
        (
          exists(
            select 1 from public.promotion_items i0
            where i0.promotion_id=p.id and trim(coalesce(i0.sku,''))<>''
          )
          and exists(
            select 1 from public.promotion_items i
            where i.promotion_id=p.id
              and trim(coalesce(i.sku,''))=trim(coalesce(ph.sku,''))
          )
        )
        or
        (
          not exists(
            select 1 from public.promotion_items i0
            where i0.promotion_id=p.id and trim(coalesce(i0.sku,''))<>''
          )
          and public.promotion_scope_match_v236105(
            coalesce(p.product_filters,'{}'::jsonb),
            ph.category,ph.subgroup,ph.sku,ph.product
          )
        )
   )
  where p.status not in ('rejected','completed')
    and p.start_date<=v_month_end
    and p.end_date>=v_month
  group by p.id
  on conflict (promotion_id,source_message_at) where source_message_at is not null
  do update set
    snapshot_at=excluded.snapshot_at,
    report_month=excluded.report_month,
    cumulative_sales=excluded.cumulative_sales,
    cumulative_qty=excluded.cumulative_qty,
    scope_version=excluded.scope_version;

  get diagnostics v_count=row_count;

  insert into public.promotion_sku_sales_snapshots(
    promotion_id,sku,snapshot_at,report_month,cumulative_sales,cumulative_qty,
    source_message_at,snapshot_kind,scope_version
  )
  select
    p.id,
    i.sku,
    v_snapshot_at,
    v_month,
    coalesce(sum(ph.revenue),0)::numeric(16,2),
    coalesce(sum(ph.qty),0)::numeric(16,2),
    p_source_message_at,
    'periodic',
    'exact_sku_qty_v236375'
  from public.promotions p
  join public.promotion_items i
    on i.promotion_id=p.id and trim(coalesce(i.sku,''))<>''
  left join public.purchase_history ph
    on ph.month=v_month
   and trim(coalesce(ph.sku,''))=trim(i.sku)
   and (
        (p.client_id is not null and ph.client_id=p.client_id)
        or lower(trim(coalesce(ph.client_name,'')))=lower(trim(coalesce(p.client_name,'')))
   )
  where p.status not in ('rejected','completed')
    and p.start_date<=v_month_end
    and p.end_date>=v_month
  group by p.id,i.sku
  on conflict (promotion_id,sku,source_message_at,snapshot_kind)
    where source_message_at is not null
  do update set
    snapshot_at=excluded.snapshot_at,
    report_month=excluded.report_month,
    cumulative_sales=excluded.cumulative_sales,
    cumulative_qty=excluded.cumulative_qty,
    scope_version=excluded.scope_version;

  return v_count;
end;
$function$;

CREATE OR REPLACE FUNCTION public.crm_capture_promotion_sku_snapshot_v236375(p_promotion_id uuid, p_kind text DEFAULT 'manual'::text, p_snapshot_at timestamp with time zone DEFAULT now())
 RETURNS integer
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'auth', 'pg_catalog'
AS $function$
declare
  v_actor public.users%rowtype;
  v_p public.promotions%rowtype;
  v_month date := date_trunc('month',(p_snapshot_at at time zone 'Europe/Minsk'))::date;
  v_count int:=0;
  v_kind text:=case when p_kind in ('approval_baseline','backfill_baseline','manual') then p_kind else 'manual' end;
begin
  select * into v_actor from public.users where id=auth.uid();
  if v_actor.id is null then raise exception 'Требуется вход в CRM' using errcode='42501'; end if;

  select * into v_p from public.promotions where id=p_promotion_id;
  if v_p.id is null then raise exception 'Акция не найдена'; end if;
  if coalesce(v_actor.role,'')<>'boss'
     and lower(trim(coalesce(v_actor.name,'')))<>lower(trim(coalesce(v_p.manager_name,''))) then
    raise exception 'Нет доступа к этой акции' using errcode='42501';
  end if;

  insert into public.promotion_sku_sales_snapshots(
    promotion_id,sku,snapshot_at,report_month,cumulative_sales,cumulative_qty,
    source_message_at,snapshot_kind,scope_version
  )
  select
    v_p.id,i.sku,p_snapshot_at,v_month,
    coalesce(sum(h.revenue),0)::numeric(16,2),
    coalesce(sum(h.qty),0)::numeric(16,2),
    case when v_kind='approval_baseline' then null else p_snapshot_at end,
    v_kind,'exact_sku_qty_v236375'
  from public.promotion_items i
  left join public.purchase_history h
    on h.month=v_month
   and h.client_id=v_p.client_id
   and trim(coalesce(h.sku,''))=trim(i.sku)
  where i.promotion_id=v_p.id and trim(coalesce(i.sku,''))<>''
  group by i.sku
  on conflict (promotion_id,sku,snapshot_kind)
    where snapshot_kind='approval_baseline'
  do update set
    snapshot_at=excluded.snapshot_at,
    report_month=excluded.report_month,
    cumulative_sales=excluded.cumulative_sales,
    cumulative_qty=excluded.cumulative_qty,
    scope_version=excluded.scope_version;

  get diagnostics v_count=row_count;
  return v_count;
end;
$function$;

CREATE OR REPLACE FUNCTION public.crm_promotion_budget_snapshot_v23630(p_promotion_id uuid)
 RETURNS jsonb
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO 'public', 'auth', 'pg_catalog'
AS $function$
declare
  v_p public.promotions%rowtype;
  v_b public.promotion_budgets%rowtype;
  v_actor public.users%rowtype;
  v_snapshot timestamptz;
  v_opening numeric:=0;
  v_accrued numeric:=0;
  v_adjustments numeric:=0;
  v_movement_spent numeric:=0;
  v_legacy_spent numeric:=0;
  v_spent numeric:=0;
  v_reserved numeric:=0;
  v_pending numeric:=0;
  v_total numeric:=0;
  v_free numeric:=0;
  v_historical_spent numeric:=0;
  v_legal_key text:='';
begin
  select * into v_actor from public.users u where u.id=auth.uid();
  if v_actor.id is null then raise exception 'Требуется вход в CRM'; end if;

  select * into v_p from public.promotions p where p.id=p_promotion_id;
  if v_p.id is null then raise exception 'Акция не найдена'; end if;

  if coalesce(v_actor.role,'')<>'boss'
     and lower(trim(coalesce(v_actor.name,'')))<>lower(trim(coalesce(v_p.manager_name,''))) then
    raise exception 'Нет доступа к бюджету этой акции';
  end if;

  v_legal_key:=public.crm_client_legal_key_v236374(v_p.client_name);

  select * into v_b
  from public.promotion_budgets b
  where b.client_id=v_p.client_id
     or (
       v_legal_key<>''
       and public.crm_client_legal_key_v236374(b.client_name)=v_legal_key
     )
  order by
    case when b.client_id=v_p.client_id then 0 else 1 end,
    coalesce(b.balance_snapshot_at,b.updated_at,b.created_at) desc nulls last
  limit 1;

  if v_b.id is null then
    return jsonb_build_object(
      'promotion_id',v_p.id,'client_id',v_p.client_id,'client_name',v_p.client_name,
      'legal_entity_key',v_legal_key,'budget_id',null,'has_budget',false,
      'requested',coalesce(v_p.requested_budget,0),
      'total',0,'spent',0,'reserved',0,'pending_other',0,'free',0,
      'shortage',greatest(0,coalesce(v_p.requested_budget,0))
    );
  end if;

  v_snapshot:=coalesce(v_b.balance_snapshot_at,v_b.updated_at,v_b.created_at,'1970-01-01'::timestamptz);
  v_opening:=coalesce(v_b.opening_balance,v_b.budget_total,0);

  select
    coalesce(sum(case when m.movement_type='accrual' then m.amount else 0 end),0),
    coalesce(sum(case when m.movement_type='adjustment' then m.amount else 0 end),0),
    coalesce(sum(case when m.movement_type='expense' then m.amount else 0 end),0)
  into v_accrued,v_adjustments,v_movement_spent
  from public.promotion_budget_movements m
  where m.budget_id=v_b.id and m.created_at>v_snapshot;

  select coalesce(sum(case when m.movement_type='expense' then m.amount else 0 end),0)
  into v_historical_spent
  from public.promotion_budget_movements m
  where m.budget_id=v_b.id and m.created_at<=v_snapshot;

  select coalesce(sum(greatest(0,coalesce(p.actual_spend,0)-coalesce((
    select sum(m2.amount) from public.promotion_budget_movements m2
    where m2.promotion_id=p.id and m2.movement_type='expense'
  ),0))),0)
  into v_legacy_spent
  from public.promotions p
  where p.budget_id=v_b.id
    and p.id<>v_p.id
    and coalesce(p.updated_at,p.created_at)>v_snapshot;

  v_spent:=v_movement_spent+v_legacy_spent;

  select coalesce(sum(greatest(0,coalesce(p.budget_reserved,0)-coalesce(p.actual_spend,0))),0)
  into v_reserved
  from public.promotions p
  where p.budget_id=v_b.id
    and p.id<>v_p.id
    and p.status in ('approved','in_work')
    and coalesce(p.approved_at,p.updated_at,p.created_at)>v_snapshot;

  select coalesce(sum(coalesce(p.requested_budget,0)),0)
  into v_pending
  from public.promotions p
  where p.id<>v_p.id
    and p.status in ('draft_manager','pending_df','pending_dfs')
    and coalesce(p.created_at,p.updated_at)>v_snapshot
    and (
      p.budget_id=v_b.id
      or (
        p.budget_id is null
        and public.crm_client_legal_key_v236374(p.client_name)=v_legal_key
      )
    );

  v_total:=v_opening+v_accrued+v_adjustments;
  v_free:=v_total-v_spent-v_reserved;

  return jsonb_build_object(
    'promotion_id',v_p.id,'client_id',v_p.client_id,'client_name',v_p.client_name,
    'legal_entity_key',v_legal_key,
    'budget_id',v_b.id,'budget_owner_client_id',v_b.client_id,'budget_owner_client_name',v_b.client_name,
    'shared_legal_entity_budget',(v_b.client_id is distinct from v_p.client_id),
    'has_budget',true,'budget_as_of',v_b.balance_as_of,'snapshot_at',v_snapshot,
    'opening',v_opening,'accrued',v_accrued,'adjustments',v_adjustments,
    'total',v_total,'spent',v_spent,'spent_after_snapshot',v_spent,
    'historical_spent_before_snapshot',v_historical_spent,
    'reserved',v_reserved,'reserved_after_snapshot',v_reserved,'pending_other',v_pending,
    'free',v_free,'requested',coalesce(v_p.requested_budget,0),
    'after_approval',v_free-coalesce(v_p.requested_budget,0),
    'shortage',greatest(0,coalesce(v_p.requested_budget,0)-v_free)
  );
end;
$function$;

